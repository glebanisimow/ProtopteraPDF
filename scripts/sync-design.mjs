// Copies the design pack into src/design/. The build depends only on src/design/.
// Usage: node scripts/sync-design.mjs   (pack path comes from design.config.json)
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const configPath = join(root, 'design.config.json');
if (!existsSync(configPath)) fail('design.config.json not found; set "designPackPath" first');
const { designPackPath: pack } = JSON.parse(readFileSync(configPath, 'utf8'));
if (!pack || !existsSync(pack)) fail(`design pack not found: ${pack}`);

const out = join(root, 'src', 'design');
mkdirSync(out, { recursive: true });

// Raster brand assets used by the app (empty state, app icon source).
const BRAND_ASSETS = {
  'glyph-claws-amber.png': 'glif-kogti-amber.png',
  'glyph-claws-bone.png': 'glif-kogti-bone.png',
  'pattern-claws-ink.png': 'uzor-kogti-ink-3x3.png',
  'app-icon.png': '07-ledorub-inv_square.png',
};

syncTokens();
syncIcons();
syncBrand();
syncFonts();
console.log(`design synced from ${pack}`);

function syncTokens() {
  const tokens = JSON.parse(readFileSync(join(pack, 'tokens.json'), 'utf8'));
  const resolve = (value, depth = 0) => {
    if (typeof value !== 'string') return value;
    return value.replace(/\{([^}]+)\}/g, (_, ref) => {
      if (depth > 8) fail(`token reference loop at {${ref}}`);
      const node = ref.split('.').reduce((n, k) => n?.[k], tokens);
      if (node?.$value === undefined) fail(`unknown token reference {${ref}}`);
      return resolve(node.$value, depth + 1);
    });
  };
  const format = (value) => (Array.isArray(value) ? value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ') : resolve(value));
  const leaves = (group, prefix) =>
    Object.entries(group)
      .filter(([k]) => !k.startsWith('$'))
      .map(([k, v]) => `  --${prefix}${k}: ${format(v.$value)};`);

  const shared = [
    ...leaves(tokens.brand, 'brand-'),
    ...leaves(tokens.font, 'font-'),
    ...leaves(tokens['font-size'], 'font-size-'),
    ...leaves(tokens.space, 'space-'),
    ...leaves(tokens.radius, 'radius-'),
    ...leaves(tokens.shadow, 'shadow-'),
    ...leaves(tokens.duration, 'duration-'),
    ...leaves(tokens.size, 'size-'),
  ];
  const dark = leaves(tokens.theme.dark, '');
  const light = leaves(tokens.theme.light, '');
  const css = `/* Generated by scripts/sync-design.mjs from the design pack. Do not edit. */
:root {
${shared.join('\n')}
}

/* Dark is the brand default; light follows the system unless the user picked a theme. */
:root {
  color-scheme: dark;
${dark.join('\n')}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme='dark']) {
    color-scheme: light;
${light.map((l) => '  ' + l).join('\n')}
  }
}

:root[data-theme='light'] {
  color-scheme: light;
${light.join('\n')}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0ms;
    --duration-base: 0ms;
  }
}
`;
  writeFileSync(join(out, 'tokens.css'), css);
}

function syncIcons() {
  const src = join(pack, 'icons');
  const dst = join(out, 'icons');
  rmSync(dst, { recursive: true, force: true });
  mkdirSync(dst, { recursive: true });
  const names = existsSync(src) ? readdirSync(src).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort() : [];
  const entries = names.map((name) => {
    copyFileSync(join(src, `${name}.svg`), join(dst, `${name}.svg`));
    const svg = readFileSync(join(src, `${name}.svg`), 'utf8').trim();
    return `  '${name}': ${JSON.stringify(svg)},`;
  });
  const ts = `// Generated by scripts/sync-design.mjs from the design pack. Do not edit.
export const ICONS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICONS;

export function hasIcon(name: string): name is IconName {
  return Object.hasOwn(ICONS, name);
}
`;
  writeFileSync(join(out, 'icons.ts'), ts);
}

function syncBrand() {
  const dst = join(out, 'brand');
  mkdirSync(dst, { recursive: true });
  for (const [to, from] of Object.entries(BRAND_ASSETS)) {
    if (!existsSync(join(pack, from))) fail(`brand asset missing in pack: ${from}`);
    copyFileSync(join(pack, from), join(dst, to));
  }
}

function syncFonts() {
  const src = join(pack, 'fonts');
  if (!existsSync(src)) return; // pack ships no fonts; UI uses system Segoe UI / Bahnschrift
  const dst = join(out, 'fonts');
  rmSync(dst, { recursive: true, force: true });
  mkdirSync(dst, { recursive: true });
  for (const f of readdirSync(src)) copyFileSync(join(src, f), join(dst, f));
}

function fail(message) {
  console.error(`sync-design: ${message}`);
  process.exit(1);
}
